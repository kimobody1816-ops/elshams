// ============================================================
// كل حركة نقدية مرتبطة بطرف (عميل أو مورد) تُسجَّل هنا، فيصير لكل قرش
// أثر يُراجَع: مين دفع، كام، إمتى، في أي خزينة، في أي وردية، ولأي فواتير.
// بدون هذا السجل كان تحصيل الدين يُنقص الرصيد ولا يترك خبراً عن المبلغ.

const PAYMENT_KINDS = {
  cust_collect: { label:'تحصيل من عميل',   dir:'in'  },
  sup_settle:   { label:'سداد لمورد',      dir:'out' },
  sale_collect: { label:'تحصيل فاتورة',    dir:'in'  },
};
const PAY_METHOD_LABELS = { cash:'نقدي', transfer:'تحويل بنكي', card:'بطاقة', check:'شيك' };

// يسجّل الدفعة ويحرّك الخزينة معاً. أي مسار مالي جديد يجب أن يمر من هنا.
async function recordPayment({ kind, partyType, partyId, partyName, amount, cashboxId,
                               method='cash', notes='', allocations=[], refId='', extra={} }){
  const dir = PAYMENT_KINDS[kind]?.dir || 'in';
  const cb  = (S.cashboxes||{})[cashboxId];
  const payId = uid();

  const data = {
    kind, dir,
    partyType, partyId, partyName: partyName||'',
    amount: +amount||0,
    method, notes,
    cashboxId:   cashboxId||'',
    cashboxName: cb?.name||'',
    // الفواتير التي أُطفئت بهذه الدفعة — تُظهر في كشف الحساب ما سُدِّد بالضبط
    allocations,
    refId,
    branchId:  CURRENT_USER?.branch||'',
    date:      new Date().toISOString().slice(0,10),
    createdAt: new Date().toISOString(),
    createdBy: CURRENT_USER?.id||'',
    createdByName: CURRENT_USER?.name||'',
    ...extra,
    ...shiftStamp(),
  };

  await dbSet('payments/'+payId, data);

  // حركة الخزينة: تحصيل يُودَع، وسداد يُصرَف
  if(cashboxId){
    await addCashboxEntry(
      cashboxId, +amount||0, dir==='in'?'deposit':'withdraw',
      `${PAYMENT_KINDS[kind]?.label||'دفعة'} — ${partyName||''}`.trim(),
      payId
    );
  }
  return payId;
}

