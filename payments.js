// إلغاء سداد / تحصيل اتسجّل بالغلط (صلاحية «إلغاء سداد» — المدير العام افتراضياً)
// ============================================================
// الدفعة مبتتمسحش: بتتعلّم «ملغاة» (مين وإمتى) وبيتعكس كل أثرها بالترتيب:
// الفواتير/أوامر الشراء اللي سدّدتها ترجع زي ما كانت، دين العميل يرجع بالمبلغ
// اللي اتشال منه فعلاً، الخزينة تاخد حركة عكسية في الوردية الحالية، ولو سداد
// مورد بيتشال المصروف التلقائي اللي اتسجّل معاه.
function canReversePayments(){ return !!CURRENT_USER && hasPerm(CURRENT_USER.role,'act-reverse-payment'); }

async function reversePayment(payId){
  const p=(S.payments||{})[payId];
  if(!p){ toast('الدفعة غير موجودة','error'); return; }
  if(p.reversed){ toast('الدفعة دي ملغاة قبل كده','warning'); return; }
  if(!canReversePayments()){ toast('ليس لديك صلاحية إلغاء السداد','error'); return; }

  const amount=+p.amount||0;
  const isIn = (p.dir||PAYMENT_KINDS[p.kind]?.dir)==='in';
  const ok=await confirm2(
    `هيتلغي ${PAYMENT_KINDS[p.kind]?.label||'الدفعة'} بمبلغ ${amount.toFixed(2)} — ${p.partyName||''}.\n`+
    (isIn ? 'المبلغ هيتخصم من الخزينة ويرجع ديناً على العميل.' : 'المبلغ هيرجع للخزينة ويرجع ديناً للمورد.'),
    'إلغاء سداد','↩️','إلغاء السداد','btn-danger');
  if(!ok) return;

  try{
    // 1) الفواتير وأوامر الشراء اللي الدفعة سدّدتها
    for(const a of (p.allocations||[])){
      const amt=+a.amount||0; if(!(amt>0)) continue;
      if(a.saleId && (S.sales||{})[a.saleId]){
        const s=S.sales[a.saleId];
        const bal=(+s.balance||0)+amt, paid=Math.max(0,(+s.amountPaid||0)-amt);
        await dbUpdate('sales/'+a.saleId,{ balance:bal, amountPaid:paid, status: bal<=0?'paid':(paid>0?'partial':'unpaid') });
      }
      if(a.poId && (S.purchaseOrders||{})[a.poId]){
        const po=S.purchaseOrders[a.poId];
        const bal=(+po.balance||0)+amt, paid=Math.max(0,(+po.amountPaid||0)-amt);
        await dbUpdate('purchaseOrders/'+a.poId,{ balance:bal, amountPaid:paid,
          payStatus: bal<=0?'completed':(paid>0?'partial':'unpaid'), updatedAt:new Date().toISOString() });
      }
    }
    // 2) دين العميل — الدفعات القديمة مفيهاش balReduced فبنرجّع المبلغ كله
    if(p.partyType==='customer' && p.partyId && (S.customers||{})[p.partyId]){
      const c=S.customers[p.partyId];
      const back = p.balReduced!==undefined ? (+p.balReduced||0) : amount;
      if(back>0) await dbUpdate('customers/'+p.partyId,{ balance:(+c.balance||0)+back });
    }
    // 3) الخزينة: حركة عكسية
    if(p.cashboxId && amount>0){
      await addCashboxEntry(p.cashboxId, amount, isIn?'withdraw':'deposit',
        `إلغاء ${PAYMENT_KINDS[p.kind]?.label||'دفعة'} — ${p.partyName||''}`.trim(), payId);
    }
    // 4) المصروف التلقائي لسداد المورد
    const exps=Object.entries(S.expenses||{}).filter(([,e])=>e.paymentId===payId && e.autoGenerated);
    for(const [eid] of exps) await dbRemove('expenses/'+eid);

    // 5) علامة الإلغاء على الدفعة نفسها
    await dbUpdate('payments/'+payId,{
      reversed:true, reversedAt:new Date().toISOString(),
      reversedBy:CURRENT_USER?.id||'', reversedByName:CURRENT_USER?.name||'',
      reversedShiftId:currentShiftId(),
    });
    toast('تم إلغاء السداد وعكس أثره ✅');
    if(_stmtCtx) renderStatement();
  }catch(e){ toast('خطأ: '+e.message,'error'); }
}

